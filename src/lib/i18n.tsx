function getInitialLanguage(): Language {
  const stored = localStorage.getItem('lang');
  if (stored === 'fr' || stored === 'en') return stored;
  return 'fr';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(getInitialLanguage);

  const persistLang = (newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem('lang', newLang);
    document.cookie = `lang=${newLang};path=/;max-age=31536000`;
  };

  const setLang = (newLang: Language) => {
    persistLang(newLang);
    supabase.auth.getSession().then(({ data: { session } }) => {
      if (session) {
        supabase.from('user_profiles').update({ language: newLang }).eq('id', session.user.id).then(() => {});
      }
    });
  };

  useEffect(() => {
    supabase.auth.getSession().then(({ data: { session } }) => {
      if (!session) return;
      supabase.from('user_profiles').select('language').eq('id', session.user.id).maybeSingle().then(({ data }) => {
        if (data?.language === 'fr' || data?.language === 'en') {
          persistLang(data.language);
        }
      });
    });
  }, []);

  const t = (key: TranslationKey, vars?: Record<string, string | number>): string => {
    let str: string = translations[lang][key] ?? translations.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return str;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
}
